#!/usr/bin/env node
/* Generates assets/js/data.gen.js from the canonical JSON in data/,
   then inlines the whole app into dist/index.html as one portable file. */

const fs = require('fs');
const path = require('path');
const R = (...p) => path.join(__dirname, ...p);

const budget  = fs.readFileSync(R('data/hollister-fy2027.json'), 'utf8');
const actions = fs.readFileSync(R('data/actions.json'), 'utf8');

fs.writeFileSync(R('assets/js/data.gen.js'),
  `/* GENERATED by build.js — edit data/*.json instead. */\n` +
  `export const BUDGET = ${budget.trim()};\n\n` +
  `export const ACTIONS = ${actions.trim()};\n`);
console.log('✓ assets/js/data.gen.js');

const read = (p) => fs.readFileSync(R(p), 'utf8');
const strip = (src) => src
  .replace(/^\s*import[^;]+;\s*$/gm, '')
  .replace(/^\s*export\s+(const|function|class|let)\s/gm, '$1 ')
  .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, '');

// app.js aliases `fmt` off the charts namespace; in a flat bundle that would
// redeclare the real one. Drop the alias and let it bind directly.
const stripApp = (src) => strip(src).replace(/^const fmt = C\.fmt;$/m, '');

const bundle = [
  '/* data */',    strip(read('assets/js/data.gen.js')),
  '/* charts */',  strip(read('assets/js/charts.js')),
  '/* engine */',  strip(read('assets/js/engine.js')),
  '/* ui */',      strip(read('assets/js/ui.js')),
  '/* app */',     stripApp(read('assets/js/app.js')),
].join('\n\n');

// The modules call each other through namespace objects; rebuild those locally.
const shims = `
const C = { fmt, donut, barsH, divergingBars, lines, waterfall, stackPair, niceMax };
const E = { METER_IDS, createState, totals, meters, meterStatus, projection,
            councilVotes, resolveBallots, score, verdicts };
`;

// A flat bundle shares one scope, so two modules declaring the same
// top-level name is a hard SyntaxError at load. Catch it here instead.
{
  const seen = {};
  const re = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(bundle))) seen[m[1]] = (seen[m[1]] || 0) + 1;
  const dupes = Object.keys(seen).filter((k) => seen[k] > 1);
  if (dupes.length) {
    console.error('✗ duplicate top-level declarations in bundle: ' + dupes.join(', '));
    process.exit(1);
  }
}

// Replacement STRINGS treat $$, $&, $` and $' as special — and the bundle is
// full of `${...}` and `$(`. Use replacer functions so every $ stays literal.
const lit = (s) => () => s;

const withShims = bundle.replace('/* app */', lit(shims + '\n/* app */'));

const html = read('index.html')
  .replace('<link rel="stylesheet" href="assets/css/app.css">',
           lit('<style>\n' + read('assets/css/app.css') + '\n</style>'))
  .replace('<script type="module" src="assets/js/app.js"></script>',
           lit('<script type="module">\n' + withShims + '\n</script>'));

fs.mkdirSync(R('dist'), { recursive: true });
fs.writeFileSync(R('dist/index.html'), html);
console.log(`✓ dist/index.html  (${(html.length / 1024).toFixed(0)} KB, single file)`);
