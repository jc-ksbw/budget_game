#!/usr/bin/env node
/* Generates assets/js/data.gen.js from the canonical JSON in data/,
   then inlines the whole app into dist/index.html as one portable file. */

const fs = require('fs');
const path = require('path');
const R = (...p) => path.join(__dirname, ...p);

const budget  = fs.readFileSync(R('data/hollister-fy2027.json'), 'utf8');
const actions = fs.readFileSync(R('data/actions.json'), 'utf8');

fs.writeFileSync(R('assets/js/data.gen.js'),
  `/* GENERATED by build.js — edit data/*.json instead. */\n` +
  `export const BUDGET = ${budget.trim()};\n\n` +
  `export const ACTIONS = ${actions.trim()};\n`);
console.log('✓ assets/js/data.gen.js');

const read = (p) => fs.readFileSync(R(p), 'utf8');
const strip = (src) => src
  .replace(/^\s*import[^;]+;\s*$/gm, '')
  .replace(/^\s*export\s+(const|function|class|let)\s/gm, '$1 ')
  .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, '');

// app.js aliases `fmt` off the charts namespace; in a flat bundle that would
// redeclare the real one. Drop the alias and let it bind directly.
const stripApp = (src) => strip(src).replace(/^const fmt = C\.fmt;$/m, '');

const bundle = [
  '/* data */',    strip(read('assets/js/data.gen.js')),
  '/* charts */',  strip(read('assets/js/charts.js')),
  '/* engine */',  strip(read('assets/js/engine.js')),
  '/* ui */',      strip(read('assets/js/ui.js')),
  '/* app */',     stripApp(read('assets/js/app.js')),
].join('\n\n');

// The modules call each other through namespace objects; rebuild those locally.
const shims = `
const C = { fmt, donut, barsH, divergingBars, lines, waterfall, stackPair, niceMax };
const E = { METER_IDS, createState, totals, meters, meterStatus, projection,
            communityReactions, resolveBallots, score, verdicts };
`;

// The shims above name functions by hand, so a rename in a module silently
// turns one into a ReferenceError that kills the whole bundle at load.
// Check every shimmed name is actually declared somewhere in it.
{
  const declared = new Set();
  const re = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(bundle))) declared.add(m[1]);
  const shimmed = (shims.match(/[{,]\s*([A-Za-z_$][\w$]*)\s*[,}]/g) || [])
    .map((x) => x.replace(/[{,}\s]/g, ''));
  const missing = shimmed.filter((n) => n && !declared.has(n));
  if (missing.length) {
    console.error('\u2717 shim references names not in the bundle: ' + missing.join(', '));
    process.exit(1);
  }
}

// A flat bundle shares one scope, so two modules declaring the same
// top-level name is a hard SyntaxError at load. Catch it here instead.
{
  const seen = {};
  const re = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(bundle))) seen[m[1]] = (seen[m[1]] || 0) + 1;
  const dupes = Object.keys(seen).filter((k) => seen[k] > 1);
  if (dupes.length) {
    console.error('✗ duplicate top-level declarations in bundle: ' + dupes.join(', '));
    process.exit(1);
  }
}

// Replacement STRINGS treat $$, $&, $` and $' as special — and the bundle is
// full of `${...}` and `$(`. Use replacer functions so every $ stays literal.
const lit = (s) => () => s;

const withShims = bundle.replace('/* app */', lit(shims + '\n/* app */'));

const html = read('index.html')
  .replace('<link rel="stylesheet" href="assets/css/app.css">',
           lit('<style>\n' + read('assets/css/app.css') + '\n</style>'))
  .replace('<script type="module" src="assets/js/app.js"></script>',
           lit('<script type="module">\n' + withShims + '\n</script>'));

fs.mkdirSync(R('dist'), { recursive: true });
fs.writeFileSync(R('dist/index.html'), html);
console.log(`✓ dist/index.html  (${(html.length / 1024).toFixed(0)} KB, single file)`);

/* ---------------------------------------------------------------
   dist/artifact.html — the same app for the Claude Artifact host,
   which supplies its own document skeleton and pads :root by the
   phone's safe-area insets. So: no doctype/head/body of our own, no
   duplicate inset padding, and side gutters written as max(16px, env()).
   --------------------------------------------------------------- */
let css = read('assets/css/app.css')
  // the host already pads :root top/bottom — don't add the insets twice
  .replace('padding: calc(env(safe-area-inset-top) + 10px) 16px 10px;',
           'padding-block: 10px; padding-left: var(--gutter); padding-right: var(--gutter);')
  .replace('position: sticky; top: 0; z-index: 40;',
           'position: sticky; top: env(safe-area-inset-top, 0px); z-index: 40;')
  .replace('padding: calc(env(safe-area-inset-top) + 28px) 20px calc(env(safe-area-inset-bottom) + 28px);',
           'padding-block: 28px; padding-left: var(--gutter); padding-right: var(--gutter);')
  .replace('.panel { padding: 16px 16px 28px; display: none; }',
           '.panel { padding-block: 16px 28px; padding-left: var(--gutter); padding-right: var(--gutter); display: none; }')
  .replace('padding-bottom: env(safe-area-inset-bottom);',
           'padding-bottom: env(safe-area-inset-bottom, 0px); padding-left: var(--gutter-0); padding-right: var(--gutter-0);')
  .replace('top: calc(env(safe-area-inset-top) + 10px); right: 14px;',
           'top: 10px; right: max(14px, env(safe-area-inset-right, 0px));')
  .replace('.app { max-width: 720px; margin: 0 auto; min-height: 100dvh; position: relative; }',
           '.app { max-width: 720px; margin: 0 auto; min-height: 100%; position: relative; }')
  .replace('  min-height: 100dvh;\n  padding-block: 28px;', '  min-height: 100%;\n  padding-block: 28px;')
  .replace('.panel { padding-inline: 22px; }', '.panel { padding-left: max(22px, env(safe-area-inset-left, 0px)); padding-right: max(22px, env(safe-area-inset-right, 0px)); }')
  .replace('.board { padding-inline: 22px; }', '.board { padding-left: max(22px, env(safe-area-inset-left, 0px)); padding-right: max(22px, env(safe-area-inset-right, 0px)); }');

// the two gutter tokens the rules above lean on
css = css.replace(':root {\n  color-scheme: light;',
  ':root {\n  color-scheme: light;\n  --gutter: max(16px, env(safe-area-inset-left, 0px));\n  --gutter-0: env(safe-area-inset-left, 0px);');

const bodyOnly = read('index.html')
  .replace(/^[\s\S]*?<body>/, '')
  .replace(/<\/body>[\s\S]*$/, '')
  .replace('<script type="module" src="assets/js/app.js"></script>', '');

const artifact =
  '<title>Balancing Hollister</title>\n' +
  '<meta name="claude:viewport-fit-sides" content="cover">\n' +
  '<style>\nhtml, body { height: 100%; }\n' + css + '\n</style>\n' +
  bodyOnly +
  '<script type="module">\n' +
  withShims.replace("padding-top:calc(env(safe-area-inset-top) + 14px)", "padding-top:14px") +
  '\n</script>\n';

fs.writeFileSync(R('dist/artifact.html'), artifact);
console.log(`✓ dist/artifact.html (${(artifact.length / 1024).toFixed(0)} KB, for the Artifact host)`);
